/**
 * Render a BSSE calculation plan into a ready-to-run folder.
 *
 * The produced set mirrors the layout used by the ABACUS water example:
 *
 *   STRU_0 / INPUT_0   full system       -> E_total
 *   STRU_1 / INPUT_1   fragment 1 + ghost basis of everything else
 *   ...
 *   run_bsse.sh        runs every single point and writes energies.txt
 *   bsse_index.json    machine readable mapping used by ACoord
 *   README_bsse.md     what was generated and how to use the result
 */

import { AbacusInput } from './abacusInput.js';
import { buildGammaOnlyKpt, createDefaultInput } from './abacusPresets.js';
import { STRUParser } from '../parsers/struParser.js';
import type { BsseCalculationPlan } from './bsseGenerator.js';

export interface BsseFileSetOptions {
  plan: BsseCalculationPlan[];
  title?: string;
  /** Existing INPUT used as the template (keeps pseudo_dir, ecutwfc, ...). */
  inputTemplate?: AbacusInput;
  pseudoDir?: string;
  orbitalDir?: string;
  gammaOnly?: boolean;
  /** Extra remarks printed in README_bsse.md (source format, added vacuum, ...). */
  notes?: string[];
}

export interface GeneratedFile {
  name: string;
  content: string;
}

export interface BsseIndexEntry {
  index: number;
  name: string;
  stru: string;
  input: string;
  ntype: number;
  species: string[];
  isReference: boolean;
}

export interface BsseIndex {
  version: number;
  title: string;
  calculations: BsseIndexEntry[];
}

/** Build every file of the BSSE set (pure function, no file system access). */
export function buildBsseFileSet(options: BsseFileSetOptions): GeneratedFile[] {
  const parser = new STRUParser();
  const files: GeneratedFile[] = [];
  const entries: BsseIndexEntry[] = [];

  for (const calculation of options.plan) {
    files.push({
      name: calculation.fileName,
      content: `${parser.serialize(calculation.structure)}\n`,
    });
    files.push({
      name: calculation.inputFileName,
      content: buildCalculationInput(calculation, options),
    });
    entries.push({
      index: calculation.index,
      name: calculation.name,
      stru: calculation.fileName,
      input: calculation.inputFileName,
      ntype: calculation.ntype,
      species: calculation.speciesLabels,
      isReference: calculation.isReference,
    });
  }

  const index: BsseIndex = {
    version: 1,
    title: options.title ?? 'ACoord BSSE calculation set',
    calculations: entries,
  };
  files.push({ name: 'bsse_index.json', content: `${JSON.stringify(index, null, 2)}\n` });
  files.push({ name: 'run_bsse.sh', content: buildRunScript(options.plan) });
  if (options.gammaOnly !== false) {
    files.push({ name: 'KPT', content: buildGammaOnlyKpt() });
  }
  files.push({ name: 'README_bsse.md', content: buildReadme(options) });
  return files;
}

/** Single-point INPUT for one calculation, with `ntype` pinned to its STRU. */
export function buildCalculationInput(
  calculation: BsseCalculationPlan,
  options: BsseFileSetOptions
): string {
  const template = options.inputTemplate ?? createDefaultInput({ kind: 'scf' });
  const input = template.clone();
  input.set('calculation', 'scf', 'single-point energy for the BSSE counterpoise correction');
  input.set('ntype', calculation.ntype, `number of species in ${calculation.fileName}`);
  input.set('cal_force', 0);
  input.set('cal_stress', 0);
  if (options.pseudoDir) {
    input.set('pseudo_dir', options.pseudoDir);
  }
  if (options.orbitalDir) {
    input.set('orbital_dir', options.orbitalDir);
  }
  return input.serialize();
}

/** Shell script that runs every single point in its own directory. */
export function buildRunScript(plan: BsseCalculationPlan[]): string {
  const indices = plan.map((calculation) => calculation.index).join(' ');
  return `#!/usr/bin/env bash
# Generated by ACoord -- counterpoise (BSSE) single-point runs.
# Usage:
#   ABACUS=/path/to/abacus bash run_bsse.sh
set -euo pipefail
ABACUS_BIN="\${ABACUS:-abacus}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
: > energies.txt
for i in ${indices}; do
  work="calc_\${i}"
  rm -rf "$work"
  mkdir -p "$work"
  cp "STRU_\${i}" "$work/STRU"
  cp "INPUT_\${i}" "$work/INPUT"
  if [ -f KPT ]; then cp KPT "$work/KPT"; fi
  ( cd "$work" && "$ABACUS_BIN" > log.txt 2>&1 )
  etot=$(grep '!FINAL_ETOT_IS' "$work/log.txt" | tail -1 | awk '{print $2}')
  echo "\${i} \${etot}" >> energies.txt
  echo "STRU_\${i}: \${etot} eV"
done
echo "All calculations finished -- energies written to energies.txt"
`;
}

function buildReadme(options: BsseFileSetOptions): string {
  const lines: string[] = [];
  lines.push('# BSSE (counterpoise) calculation set');
  lines.push('');
  lines.push(options.title ? `_${options.title}_` : '_Generated by ACoord_');
  lines.push('');
  lines.push('Each `STRU_i` keeps the nuclei of one fragment and all other atoms as');
  lines.push('basis-only "empty" centres (`X_empty`). `INPUT_i` has `ntype` set to the');
  lines.push('number of species in that STRU, so every run is self-contained.');
  lines.push('');
  lines.push('| file | ntype | species | meaning |');
  lines.push('| --- | --- | --- | --- |');
  for (const calculation of options.plan) {
    const meaning = calculation.isReference
      ? 'full system (E_total)'
      : `fragment ${calculation.name} in the full basis (E_${calculation.index})`;
    lines.push(
      `| \`${calculation.fileName}\` | ${calculation.ntype} | ${calculation.speciesLabels.join(', ')} | ${meaning} |`
    );
  }
  lines.push('');
  if (options.notes && options.notes.length > 0) {
    lines.push('## Notes');
    lines.push('');
    for (const note of options.notes) {
      lines.push(`- ${note}`);
    }
    lines.push('');
  }
  lines.push('## Run');
  lines.push('');
  lines.push('```bash');
  lines.push('ABACUS=/path/to/abacus bash run_bsse.sh');
  lines.push('```');
  lines.push('');
  lines.push('Outputs land in `calc_<i>/log.txt` and the total energies are collected in');
  lines.push('`energies.txt`.');
  lines.push('');
  lines.push('## Result');
  lines.push('');
  lines.push('```text');
  lines.push('E_BSSE = E_total - sum_i E_i');
  lines.push('```');
  lines.push('');
  lines.push('Open the folder in VS Code and run **ACoord: Collect BSSE Energies** to');
  lines.push('evaluate the sum and write `bsse_result.md`.');
  lines.push('');
  return lines.join('\n');
}
